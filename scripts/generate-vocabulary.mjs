#!/usr/bin/env node
// Generates every vocabulary artefact from standards/vocabulary.yaml
// (asset-inventory ADR-0010 D2; DCIM BUILD_PLAN row 0.1).
//
// Outputs:
//   shared/dcim/objectkind_gen.go                       (whole file)
//   packages/primitives/src/dcim/object-kinds.gen.ts    (whole file)
//   api/openapi/components/object-kind.yaml             (whole file; the standalone ObjectKind schema)
//   api/openapi/inventory-service.openapi.yaml          (1 generated region: components.schemas.ObjectKind)
//   docsv4/core/concepts/vocabulary.md                  (1 generated region; the preamble is hand-written)
//
// Why the OpenAPI schema is both a component file AND an inline region: no
// OpenAPI document in this repo uses an external $ref, and openapi-typescript,
// the Go contract tests and the lint step all read one self-contained file per
// service. The inline region (same shape as AssetClassKey) is what the
// contract consumes; the component file is the standalone copy other specs can
// $ref once the toolchain resolves external refs. --check diffs both.
//
// Run via `make generate`; `make audit` runs `--check` and fails on drift.
// `--root <dir>` points the generator at another tree (the tests use it).
import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import yaml from 'yaml';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const KEY = /^[a-z][a-z0-9_]*$/;
// Reserved nouns that are also an ObjectKind: they are referenced by existing
// tables (ADR-0002) rather than created by the DCIM build. The reserved block
// of the YAML carries no table, so the pairing lives here and the audit checks
// both tables exist in schema.sql.
export const RESERVED_KINDS = { asset: 'assets', endpoint: 'asset_endpoints' };

// Plural nouns that do not take a regular suffix. `chassis` is its own plural.
const INVARIANT = new Set(['chassis']);

export function pascal(key) {
  return key.split('_').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
}

// Table name = plural of the key (VOCABULARY.md rule 5). Only the last
// underscore-separated word inflects.
export function pluralKey(key) {
  const parts = key.split('_');
  const w = parts.pop();
  let p;
  if (INVARIANT.has(w)) p = w;
  else if (/(s|x|z|ch|sh)$/.test(w)) p = `${w}es`;
  else if (/[^aeiou]y$/.test(w)) p = `${w.slice(0, -1)}ies`;
  else p = `${w}s`;
  return [...parts, p].join('_');
}

export function loadVocabulary(root) {
  const file = path.join(root, 'standards', 'vocabulary.yaml');
  const reg = yaml.parse(fs.readFileSync(file, 'utf8'));
  const errors = [];
  const seen = new Set();
  const kinds = [];

  const push = (k) => {
    if (seen.has(k.key)) { errors.push(`duplicate key: ${k.key}`); return; }
    seen.add(k.key);
    kinds.push(k);
  };

  const reserved = reg.reserved || [];
  for (const [key, table] of Object.entries(RESERVED_KINDS)) {
    const r = reserved.find((x) => x.key === key);
    if (!r) { errors.push(`reserved noun "${key}" is missing (it is an ObjectKind)`); continue; }
    push({
      key, label: r.label, plural: r.plural, table, phase: '0',
      netbox: r.netbox || '', uiLabel: r.ui_label_override || r.label,
      meaning: r.meaning || '', reserved: true,
    });
  }
  for (const o of reg.objects || []) {
    if (!KEY.test(o.key || '')) { errors.push(`bad object key: ${JSON.stringify(o.key)}`); continue; }
    if (!o.label || !o.plural) errors.push(`${o.key}: label and plural are required`);
    if (o.table !== null && o.table !== undefined && o.table !== pluralKey(o.key)) {
      errors.push(`${o.key}: table "${o.table}" must be the plural of the key ("${pluralKey(o.key)}")`);
    }
    for (const [field, want] of [['go_type', pascal(o.key)], ['ts_type', pascal(o.key)], ['openapi', pascal(o.key)]]) {
      if (o[field] !== undefined && o[field] !== want) {
        errors.push(`${o.key}: ${field} "${o[field]}" must be the PascalCase of the key ("${want}")`);
      }
    }
    if (o.phase === undefined) errors.push(`${o.key}: phase is required`);
    push({
      key: o.key, label: o.label, plural: o.plural, table: o.table ?? null,
      phase: String(o.phase), netbox: o.netbox || '',
      uiLabel: o.ui_label_override || o.label,
      meaning: '', why: o.why || '', reserved: false,
    });
  }
  const pas = new Map();
  for (const k of kinds) {
    const p = pascal(k.key);
    if (pas.has(p)) errors.push(`keys ${pas.get(p)} and ${k.key} collide on the Go name ${p}`);
    pas.set(p, k.key);
  }
  const currentPhase = reg.current_phase ?? 0;
  if (!Number.isInteger(currentPhase) || currentPhase < 0) errors.push('current_phase must be a non-negative integer');
  return { reg, kinds, errors, currentPhase };
}

const HEADER = 'Code generated by scripts/generate-vocabulary.mjs from standards/vocabulary.yaml. DO NOT EDIT — edit the YAML and run `make generate`.';

function emitGo(kinds) {
  const q = (s) => JSON.stringify(s);
  const w = Math.max(...kinds.map((k) => `ObjectKind${pascal(k.key)}`.length));
  const consts = kinds.map((k) => `\t${`ObjectKind${pascal(k.key)}`.padEnd(w)} ObjectKind = ${q(k.key)}`).join('\n');
  const all = kinds.map((k) => `\tObjectKind${pascal(k.key)},`).join('\n');
  const rows = kinds.map((k) => `\t${`ObjectKind${pascal(k.key)}:`.padEnd(w + 1)} {label: ${q(k.label)}, plural: ${q(k.plural)}, table: ${q(k.table ?? '')}, phase: ${q(k.phase)}, netbox: ${q(k.netbox)}},`).join('\n');
  return `// ${HEADER}

package dcim

// ObjectKind is the canonical key of an inventory object noun
// (standards/vocabulary.yaml). Every polymorphic field — a tag's object,
// a journal entry's subject, a change's target, a cable termination — carries
// one of these.
type ObjectKind string

// The object kinds, in registry order.
const (
${consts}
)

// AllObjectKinds lists every ObjectKind in registry order.
var AllObjectKinds = []ObjectKind{
${all}
}

type objectKindInfo struct {
	label, plural, table, phase, netbox string
}

var objectKindInfos = map[ObjectKind]objectKindInfo{
${rows}
}

// Label is the UI singular label ("Business Unit").
func (k ObjectKind) Label() string { return objectKindInfos[k].label }

// Plural is the UI plural label ("Business Units").
func (k ObjectKind) Plural() string { return objectKindInfos[k].plural }

// Table is the Postgres table, or "" when the kind is not a table.
func (k ObjectKind) Table() string { return objectKindInfos[k].table }

// Phase is the BUILD_PLAN phase in which the table ships ("planned" if unscheduled).
func (k ObjectKind) Phase() string { return objectKindInfos[k].phase }

// NetBox is the NetBox object this kind maps to, or "" when there is none.
func (k ObjectKind) NetBox() string { return objectKindInfos[k].netbox }

// ParseObjectKind returns the kind for a registry key.
func ParseObjectKind(s string) (ObjectKind, bool) {
	k := ObjectKind(s)
	_, ok := objectKindInfos[k]
	return k, ok
}
`;
}

function emitTS(kinds) {
  const q = (s) => JSON.stringify(s);
  const list = kinds.map((k) => `  ${q(k.key)},`).join('\n');
  const rows = kinds.map((k) => `  ${k.key}: { label: ${q(k.label)}, plural: ${q(k.plural)}, uiLabel: ${q(k.uiLabel)} },`).join('\n');
  return `// ${HEADER}

export const OBJECT_KINDS = [
${list}
] as const;

export type ObjectKind = (typeof OBJECT_KINDS)[number];

/** uiLabel honours ui_label_override (e.g. "Platform (OS)"); use it in the UI. */
export const OBJECT_KIND_LABELS: Record<
  ObjectKind,
  { label: string; plural: string; uiLabel: string }
> = {
${rows}
};
`;
}

const OPENAPI_DESC = 'Canonical key of an inventory object noun (standards/vocabulary.yaml, ADR-0010 D2). Used by every polymorphic reference.';

function emitComponent(kinds) {
  const enumLines = kinds.map((k) => `  - ${k.key}`).join('\n');
  return `# ${HEADER}
type: string
description: '${OPENAPI_DESC}'
enum:
${enumLines}
`;
}

function emitSpecRegion(kinds) {
  const enumLines = kinds.map((k) => `      - ${k.key}`).join('\n');
  return `    ObjectKind:
      type: string
      description: '${OPENAPI_DESC}'
      enum:
${enumLines}`;
}

function cleanNetbox(nb) {
  // The glossary names the NetBox object, not the mapping commentary.
  return nb.replace(/\s*\(.*$/, '').trim();
}

// "An Interface", "An FHRP Group", "A MAC Address" — the first word decides.
const AN_ACRONYMS = new Set(['FHRP', 'RIR', 'L2VPN']);
function article(label) {
  const first = label.split(' ')[0];
  return /^[AEIOU]/.test(first) || AN_ACRONYMS.has(first) ? 'An' : 'A';
}

function emitDocRegion(kinds) {
  const rows = kinds.map((k) => {
    const label = k.uiLabel;
    const meaning = k.reserved && k.meaning
      ? k.meaning.replace(/\s*\(ADR-[^)]*\)/g, '')
      : `${article(k.label)} ${k.label}.`;
    const nb = cleanNetbox(k.netbox);
    return `| ${label} | ${k.plural} | ${meaning} | ${nb ? `\`${nb}\`` : '—'} |`;
  });
  return `| Term | Plural | Meaning | NetBox counterpart |
|---|---|---|---|
${rows.join('\n')}`;
}

const DOC_PREAMBLE = `# Vocabulary

Vista Platform uses one set of nouns for the objects it inventories, in the
user interface, the API and these docs. Where an industry data model already
has a name for a thing, Vista uses it. This page lists the terms.

The NetBox column shows the object each term corresponds to when you exchange
data with a NetBox instance. A dash means there is no counterpart.

`;
const DOC_BEGIN = '<!-- BEGIN GENERATED: vocabulary — from standards/vocabulary.yaml (make generate) -->';
const DOC_END = '<!-- END GENERATED: vocabulary -->';

function spliceRegion(src, begin, end, body, what) {
  const bi = src.indexOf(begin);
  const ei = src.indexOf(end);
  if (bi === -1 || ei === -1 || ei < bi) {
    throw new Error(`region markers for "${what}" not found (or out of order) — expected:\n  ${begin}\n  ${end}`);
  }
  return `${src.slice(0, bi + begin.length)}\n${body}\n${src.slice(ei)}`;
}

export function buildOutputs(root) {
  const { kinds, errors } = loadVocabulary(root);
  if (errors.length) throw new Error(`vocabulary.yaml invalid:\n  ${errors.join('\n  ')}`);

  const specPath = path.join(root, 'api', 'openapi', 'inventory-service.openapi.yaml');
  const spec = spliceRegion(
    fs.readFileSync(specPath, 'utf8'),
    '    # BEGIN GENERATED: object kind — from standards/vocabulary.yaml (make generate)',
    '    # END GENERATED: object kind',
    emitSpecRegion(kinds), 'object kind',
  );

  const docPath = path.join(root, 'docsv4', 'core', 'concepts', 'vocabulary.md');
  const docSrc = fs.existsSync(docPath) ? fs.readFileSync(docPath, 'utf8') : `${DOC_PREAMBLE}${DOC_BEGIN}\n${DOC_END}\n`;
  const doc = spliceRegion(docSrc, DOC_BEGIN, DOC_END, emitDocRegion(kinds), 'vocabulary glossary');

  return [
    [path.join(root, 'shared', 'dcim', 'objectkind_gen.go'), emitGo(kinds)],
    [path.join(root, 'packages', 'primitives', 'src', 'dcim', 'object-kinds.gen.ts'), emitTS(kinds)],
    [path.join(root, 'api', 'openapi', 'components', 'object-kind.yaml'), emitComponent(kinds)],
    [specPath, spec],
    [docPath, doc],
  ];
}

function main() {
  const argv = process.argv.slice(2);
  const checkOnly = argv.includes('--check');
  const ri = argv.indexOf('--root');
  const root = ri >= 0 ? path.resolve(argv[ri + 1]) : path.resolve(__dirname, '..');
  let outputs;
  try {
    outputs = buildOutputs(root);
  } catch (e) {
    console.error(`vocabulary: ${e.message}`);
    process.exit(1);
  }
  if (checkOnly) {
    const stale = outputs
      .filter(([p, c]) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '') !== c)
      .map(([p]) => path.relative(root, p));
    if (stale.length) {
      console.error(`vocabulary: out of date — run \`make generate\`:\n  ${stale.join('\n  ')}`);
      process.exit(1);
    }
    console.log(`vocabulary check OK (${outputs.length} artefacts)`);
    return;
  }
  for (const [p, c] of outputs) {
    fs.ensureDirSync(path.dirname(p));
    fs.writeFileSync(p, c);
    console.log(`Generated: ${path.relative(root, p)}`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
