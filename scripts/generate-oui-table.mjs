#!/usr/bin/env node
// Generates the OUI → vendor lookup table from standards/oui-vendors.csv
// (asset-inventory ADR-0004 D2, workstream 2.5). Outputs:
//   shared/hostobs/oui_gen.go
// Run via `make generate`; `make audit` fails on drift (--check mode).
//
// The table is compiled into the sensor and pcap-processor so that vendor
// resolution needs no network call — the sensor runs on an air-gapped segment
// as often as not, and an OUI lookup that reaches the internet would be both a
// privacy leak and a source of "works on my LAN" behaviour.
import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';
import { goStr, fail as sharedFail } from './lib/registry-codegen.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..');

const fail = (msg) => sharedFail('oui-table', msg);

const PREFIX_RE = /^[0-9A-F]{2}:[0-9A-F]{2}:[0-9A-F]{2}$/;

/**
 * Parses the CSV into [{prefix, vendor}], rejecting anything malformed.
 * Strict on purpose: a silently-skipped bad row is a vendor that quietly stops
 * resolving, which nobody notices until a device is filed under no
 * manufacturer.
 */
function parse(csv) {
  const rows = [];
  /** @type {Map<string, {vendor: string, line: number}>} */
  const seen = new Map();
  const lines = csv.split('\n');

  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i].trim();
    if (!raw || raw.startsWith('#')) continue;
    if (raw === 'prefix,vendor') continue;

    const comma = raw.indexOf(',');
    if (comma < 0) fail(`line ${i + 1}: expected "prefix,vendor", got ${JSON.stringify(raw)}`);

    const prefix = raw.slice(0, comma).trim();
    const vendor = raw.slice(comma + 1).trim();

    if (!PREFIX_RE.test(prefix)) {
      fail(`line ${i + 1}: bad OUI prefix ${JSON.stringify(prefix)} (want AA:BB:CC, upper case hex)`);
    }
    if (!vendor) fail(`line ${i + 1}: empty vendor for ${prefix}`);
    if (vendor.length > 64) fail(`line ${i + 1}: vendor name longer than 64 chars: ${vendor}`);
    const prior = seen.get(prefix);
    if (prior) {
      fail(
        `line ${i + 1}: duplicate prefix ${prefix} (already mapped to ${JSON.stringify(prior.vendor)} on line ${prior.line})`,
      );
    }
    seen.set(prefix, { vendor, line: i + 1 });
    rows.push({ prefix, vendor });
  }

  if (!rows.length) fail('no OUI rows found');
  return rows;
}

function render(rows) {
  // Sorted so the generated file is stable under CSV reordering, and so a
  // reviewer reading the diff sees a real change rather than a reshuffle.
  const sorted = [...rows].sort((a, b) => (a.prefix < b.prefix ? -1 : a.prefix > b.prefix ? 1 : 0));
  const vendors = new Set(sorted.map((r) => r.vendor));

  const entries = sorted
    .map((r) => `\t${goStr(r.prefix.toLowerCase())}: ${goStr(r.vendor)},`)
    .join('\n');

  return `// Code generated by scripts/generate-oui-table.mjs from
// standards/oui-vendors.csv. DO NOT EDIT — edit the CSV and run
// \`make generate\`.

package hostobs

import "strings"

// ouiVendors maps a 24-bit OUI, rendered lower-case as "aa:bb:cc", to the
// manufacturer it is registered to.
//
// ${sorted.length} prefixes covering ${vendors.size} manufacturers: a curated subset
// of the IEEE MA-L registry, not the whole of it. See standards/oui-vendors.csv
// for what that choice costs, and why an absent prefix means "not determined"
// rather than "unknown manufacturer".
var ouiVendors = map[string]string{
${entries}
}

// VendorForMAC returns the manufacturer registered to the MAC's OUI, or "" when
// the prefix is not in the compiled table.
//
// "" is an answer meaning NOT DETERMINED. It must never be rendered as
// "Unknown" on an asset: the difference between "we looked and the registry
// does not list this prefix" and "we did not look" is the difference the
// consumer needs to decide whether to ask a different collector.
//
// A locally-administered address (a randomised phone MAC, a container veth) is
// looked up like any other and will normally miss, which is correct. The few
// hits are hypervisor prefixes such as 52:54:00, where the answer describes the
// virtualisation platform rather than any hardware — [HostObservation] carries
// MACLocallyAdministered so a consumer can tell.
func VendorForMAC(mac string) string {
	normalized := NormalizeMAC(mac)
	if len(normalized) < 8 {
		return ""
	}
	return ouiVendors[strings.ToLower(normalized[:8])]
}

// OUICount reports how many prefixes the compiled table holds. Exported for
// the package's own test, which asserts the table is non-trivially populated —
// a generator that silently emitted an empty map would otherwise leave every
// vendor lookup returning "" with nothing failing.
func OUICount() int { return len(ouiVendors) }
`;
}

async function main() {
  const checkOnly = process.argv.includes('--check');
  const csvPath = path.resolve(root, 'standards', 'oui-vendors.csv');
  const outPath = path.resolve(root, 'shared', 'hostobs', 'oui_gen.go');

  const rows = parse(await fs.readFile(csvPath, 'utf8'));
  const want = render(rows);

  if (checkOnly) {
    const current = (await fs.pathExists(outPath)) ? await fs.readFile(outPath, 'utf8') : '';
    if (current !== want) {
      fail(`${path.relative(root, outPath)} is out of date — run \`make generate\``);
    }
    console.log(`oui-table check OK (${rows.length} prefixes)`);
    return;
  }

  await fs.ensureDir(path.dirname(outPath));
  await fs.writeFile(outPath, want);
  console.log(`Generated: ${path.relative(root, outPath)} (${rows.length} OUI prefixes)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
