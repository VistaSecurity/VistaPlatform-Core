// mountDcimCatalogueRoutes mounts the device catalogue (DCIM BUILD_PLAN row
// 2.2) under /inventory-service/dcim on the JWT-authenticated v2 group: reads
// behind dcim.read, writes behind dcim.manage (row 0.6's permissions), with
// changes.Middleware putting the actor and request id on the context for the
// change record. Platform-seeded rows are refused on write by the service
// (403 read_only), not by a gate: a tenant admin may write the tenant's own.
//
// One literal registration per route, so the spec-route scanner
// (shared/api/spectest) sees each path. main() calls this;
// dcim_catalogue_routes_test.go drives the same function over every route.
