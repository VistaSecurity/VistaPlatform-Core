// Package ratingsgen generates browser-safe twins of the Go rating owners.
package ratingsgen

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/vistasecurity/vistaplatform/shared/healthbands"
	"github.com/vistasecurity/vistaplatform/shared/riskbands"
	"github.com/vistasecurity/vistaplatform/shared/severity"
	"github.com/vistasecurity/vistaplatform/shared/strength"
)

type Risk struct {
	Label    string            `json:"label"`
	Min      int               `json:"min"`
	Severity severity.Severity `json:"severity"`
}
type Severity struct {
	Value         severity.Severity `json:"value"`
	Label         string            `json:"label"`
	Rank          int               `json:"rank"`
	ControlWeight int               `json:"controlWeight"`
}
type Health struct {
	Value healthbands.Band `json:"value"`
	Label string           `json:"label"`
	Min   float64          `json:"min"`
}
type Definitions struct {
	Strength []strength.Definition `json:"strength"`
	Risk     []Risk                `json:"risk"`
	Severity []Severity            `json:"severity"`
	Health   []Health              `json:"health"`
}

func Values() Definitions {
	out := Definitions{Strength: strength.Definitions()}
	for _, b := range riskbands.RiskBands {
		out.Risk = append(out.Risk, Risk{b.Label, b.Min, riskbands.Severity(b.Min)})
	}
	for _, b := range severity.Definitions() {
		out.Severity = append(out.Severity, Severity{b.Value, b.Label, b.Rank, b.ControlWeight})
	}
	for _, b := range healthbands.Definitions() {
		out.Health = append(out.Health, Health{b.Value, b.Label, b.Min})
	}
	return out
}
func JSON() []byte {
	out, err := json.MarshalIndent(Values(), "", "  ")
	if err != nil {
		panic(err)
	}
	return append(out, '\n')
}
func TypeScript() []byte {
	v := Values()
	var b strings.Builder
	b.WriteString("// Code generated by shared/ratingsgen/cmd/gen-ratings; DO NOT EDIT.\n// React-free definitions. Availability belongs to the field-specific adapter.\n\n")
	write := func(name string, value any) {
		out, err := json.MarshalIndent(value, "", "  ")
		if err != nil {
			panic(err)
		}
		fmt.Fprintf(&b, "export const %s = %s as const;\n\n", name, out)
	}
	write("RISK_BANDS", v.Risk)
	write("SEVERITIES", v.Severity)
	write("HEALTH_BANDS", v.Health)
	write("STRENGTHS", v.Strength)
	b.WriteString(`export type RiskLevel = (typeof RISK_BANDS)[number]['label'];
export type Severity = (typeof SEVERITIES)[number]['value'];
export type Strength = (typeof STRENGTHS)[number]['value'];
export type HealthBand = (typeof HEALTH_BANDS)[number]['value'];
export type ControlSeverity = Exclude<Severity, 'info'>;
export const CONTROL_SEVERITIES: readonly ControlSeverity[] = SEVERITIES.filter(band => band.controlWeight > 0).map(band => band.value as ControlSeverity);
export const RISK_LEVELS: readonly RiskLevel[] = RISK_BANDS.map(band => band.label);

// Measured numeric risk only. Callers retain their assessment/coverage signal.
export function riskLevelFromScore(score: number): RiskLevel {
  return RISK_BANDS.find(band => score >= band.min)?.label ?? 'Informational';
}
export function parseSeverity(value: string): Severity | null {
  return SEVERITIES.find(band => band.value === value)?.value ?? null;
}
export function severityRank(value: Severity): number | null {
  return SEVERITIES.find(band => band.value === value)?.rank ?? null;
}
export function severityLabel(value: Severity): string | null {
  return SEVERITIES.find(band => band.value === value)?.label ?? null;
}
// Info is a finding severity, never a zero-weight compliance control.
export function controlWeight(value: Severity): number | null {
  const weight = SEVERITIES.find(band => band.value === value)?.controlWeight;
  return weight ? weight : null;
}
export function strengthRank(value: string): number | null {
  return STRENGTHS.find(band => band.value === value)?.rank ?? null;
}
export function strengthLabel(value: Strength): string | null {
  return STRENGTHS.find(band => band.value === value)?.label ?? null;
}
export function healthBandFromScore(score: number | null | undefined): HealthBand | null {
  if (score == null || !Number.isFinite(score) || score < 0 || score > 100) return null;
  return HEALTH_BANDS.find(band => score >= band.min)?.value ?? null;
}
export function healthLabel(value: HealthBand): string | null {
  return HEALTH_BANDS.find(band => band.value === value)?.label ?? null;
}
`)
	return []byte(b.String())
}
